using System.IO;
using System.Text.Json.Nodes;
using SnipToss.App;
using Xunit;

namespace AppTests;

/// <summary>
/// Which language is used: runs the same golden file as the UI's i18n.tsx
/// (tests/golden/locale.json, also read by packages/web/test/i18n.test.ts)
/// </summary>
public class LocaleTests
{
    static JsonNode Golden(string name = "locale.json")
    {
        for (var d = new DirectoryInfo(AppContext.BaseDirectory); d is not null; d = d.Parent)
        {
            var file = Path.Combine(d.FullName, "tests", "golden", name);
            if (File.Exists(file)) return JsonNode.Parse(File.ReadAllText(file))!;
        }
        throw new InvalidOperationException($"tests/golden/{name} not found");
    }

    /// <summary>
    /// The messages the shell uses (brand / category / shell / capture / ai / markColor) format to exactly the same text as the UI's
    /// intl-messageformat (ADR-0001 item 3).
    /// The golden file tests/golden/messages.json is generated by packages/web/test/messages-golden.test.ts
    /// and covers the plural and select cases
    /// </summary>
    [Fact]
    public void Messages_format_character_for_character_the_same_as_the_UI()
    {
        var cases = Golden("messages.json")["cases"]!.AsArray();
        Assert.NotEmpty(cases);
        var wrong = new List<string>();
        foreach (var c in cases)
        {
            var args = c!["args"]!.AsObject()
                .Select(a => (a.Key, a.Value!.GetValueKind() == System.Text.Json.JsonValueKind.Number ? (object)(long)a.Value : (string)a.Value!))
                .ToArray();
            var (locale, key, want) = ((string)c["locale"]!, (string)c["key"]!, (string)c["text"]!);
            var got = Locale.In(locale, key, args);
            if (got != want) wrong.Add($"{locale} {key} {c["args"]!.ToJsonString()}: 应为「{want}」，实际「{got}」");
        }
        Assert.True(wrong.Count == 0, string.Join("\n", wrong));
    }

    [Fact]
    public void Languages_selectable_by_follow_system_match_the_golden_file()
    {
        Assert.Equal(Golden()["followSystem"]!.AsArray().Select(n => (string)n!), Locale.FollowSystem);
    }

    [Fact]
    public void System_language_tags_map_to_supported_languages()
    {
        foreach (var c in Golden()["match"]!.AsArray())
            Assert.True((string)c![1]! == Locale.Match((string?)c[0]), $"{c[0]} → {c[1]}, got {Locale.Match((string?)c[0])}");
    }

    [Fact]
    public void A_language_chosen_in_settings_wins_and_follow_system_looks_at_the_system()
    {
        foreach (var c in Golden()["resolve"]!.AsArray())
        {
            var (pref, system, want) = ((string?)c!["pref"], (string)c["system"]!, (string)c["want"]!);
            Assert.True(want == Locale.Resolve(pref, system), $"Setting {pref}, system {system} → {want}, got {Locale.Resolve(pref, system)}");
        }
    }

    [Theory]
    [InlineData("zh-CN", "Microsoft YaHei UI")]
    [InlineData("en", "Microsoft YaHei UI")]
    [InlineData("zh-TW", "Microsoft JhengHei UI")]
    [InlineData("ja", "Yu Gothic UI, Meiryo UI")]
    [InlineData("ko", "Malgun Gothic")]
    public void Native_UI_CJK_fonts_follow_the_interface_language_matching_the_web_UIs_font_variable(string lang, string cjk)
    {
        Assert.Equal(cjk, Locale.CjkFont(lang));
        // --font-cjk in the web UI's styles.css lists the same fonts
        var css = File.ReadAllText(Path.Combine(RepoRoot(), "packages", "web", "src", "styles.css"));
        Assert.Contains($"--font-cjk: \"{cjk.Replace(", ", "\", \"", StringComparison.Ordinal)}\";", css, StringComparison.Ordinal);
    }

    static string RepoRoot()
    {
        for (var d = new DirectoryInfo(AppContext.BaseDirectory); d is not null; d = d.Parent)
            if (File.Exists(Path.Combine(d.FullName, "tests", "golden", "locale.json"))) return d.FullName;
        throw new InvalidOperationException("repo root not found");
    }

    [Fact]
    public void Every_message_file_compiled_into_the_app_is_a_supported_language()
    {
        var names = typeof(Locale).Assembly.GetManifestResourceNames().Where(n => n.StartsWith("locales.", StringComparison.Ordinal)).ToList();
        Assert.Contains("locales.zh-CN.json", names);
        Assert.Contains("locales.en.json", names);
        foreach (var n in names) Assert.Contains(n["locales.".Length..^".json".Length], Locale.All);
    }

    /// <summary>
    /// Tray text stays within Windows' limits (NOTIFYICONDATA szTip / szInfoTitle / szInfo: 127 characters for the hover text,
    /// 63 for the balloon title, 255 for the body); anything longer loses its second half.
    /// The body is measured with the longest shortcut description (key names follow the language, e.g. German "Strg Alt Umschalt Rücktaste").
    /// The "still running in the background" text used to exceed the limit in German, French, Italian, Russian and Spanish
    /// </summary>
    [Fact]
    public void Tray_text_stays_within_Windows_limits()
    {
        var wrong = new List<string>();
        foreach (var l in Locale.All)
        {
            var app = Locale.In(l, "brand.name");
            var keys = $"{Locale.In(l, "keycap.Ctrl")} Alt {Locale.In(l, "keycap.Shift")} {Locale.In(l, "keycap.Backspace")}";
            var hint = Locale.In(l, "shell.tray.hotkeyHint", ("keys", keys));
            // Reasons the shortcut could not be registered (GlobalHotKey.Set): take the longest
            var reason = new[] { "shell.hotkey.taken", "shell.hotkey.invalid", "shell.hotkey.shiftOnly" }.Select(k => Locale.In(l, k, ("keys", keys))).MaxBy(s => s.Length)!;
            (string What, string Text, int Max)[] texts =
            [
                ("悬停文字", app, 127),
                ("「仍在后台运行」标题", Locale.In(l, "shell.tray.stillRunning", ("app", app)), 63),
                ("「仍在后台运行」正文", Locale.In(l, "shell.tray.stillRunningBody", ("hotkeyHint", hint)), 255),
                ("「快捷键没注册上」标题", Locale.In(l, "shell.tray.hotkeyFailed"), 63),
                ("「快捷键没注册上」正文", Locale.In(l, "shell.tray.hotkeyFailedBody", ("reason", reason)), 255),
            ];
            foreach (var (what, text, max) in texts)
                if (text.Length > max) wrong.Add($"{l} {what}：{text.Length} 个字符，上限 {max}：{text}");
        }
        Assert.True(wrong.Count == 0, string.Join("\n", wrong));
    }

    [Fact]
    public void Message_lookup_follows_the_language_falls_back_to_English_for_untranslated_and_returns_the_key_for_unknown()
    {
        Assert.Equal("覆盖画面大部分", Locale.In("zh-CN", "ai.where.most"));
        Assert.Equal("covering most of the frame", Locale.In("en", "ai.where.most"));
        Assert.Equal(Locale.In("en", "ai.where.most"), Locale.In("xx", "ai.where.most")); // a language with no message file
        Assert.NotEqual(Locale.In("zh-CN", "ai.where.most"), Locale.In("en", "ai.where.most"));
        Assert.Equal("no.such.key", Locale.In("zh-CN", "no.such.key"));
    }
}

/// <summary>Use changes the app-wide current language: run it alone, not in parallel with other tests (Screen Capture text, position wording)</summary>
[CollectionDefinition("Locale.Current", DisableParallelization = true)]
public class LocaleCurrentGroup;

[Collection("Locale.Current")]
public class LocaleUseTests
{
    [Fact]
    public void Changing_the_language_in_settings_switches_the_current_language_and_notifies_and_no_change_does_not_notify()
    {
        var before = Locale.Current;
        var changed = 0;
        void OnChanged() => changed++;
        Locale.Changed += OnChanged;
        try
        {
            Locale.Use("en");
            Assert.Equal("en", Locale.Current);
            Assert.Equal(Locale.In("en", "ai.where.most"), Locale.T("ai.where.most"));
            Locale.Use("en");
            Assert.Equal(1, changed);
            Locale.Use("zh-CN");
            Assert.Equal("zh-CN", Locale.Current);
            Assert.Equal(2, changed);
            // "Follow system" reads the display language of the machine running the tests (any language will do)
            Locale.Use("system");
            Assert.Equal(Locale.Resolve(null, System.Globalization.CultureInfo.CurrentUICulture.Name), Locale.Current);
        }
        finally
        {
            Locale.Changed -= OnChanged;
            Locale.Use(before);
        }
    }
}
