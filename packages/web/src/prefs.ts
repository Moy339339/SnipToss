import { createContext, useContext } from "react";
import { isMarkColor, NOTE_SECTIONS, type AnnotationCategory, type MaterialKind, type NoteSection } from "@sniptoss/core";

// Settings. Stored in the shell's settings.json (Prefs in %APPDATA%\SnipToss\settings.json).
// The shell itself reads some of them: kinds, moreFormats, skipDirs, markColor, defaultCategory, promptExtra, language, updateCheck (app/Settings.cs); renaming one means changing both sides.

export interface Prefs {
  // General
  /** Interface language: "system" = follow the Windows display language, otherwise one of LOCALES in i18n.tsx */
  language: string;
  /** Note author name; empty = use the Windows user name */
  author: string;
  /** Interface zoom */
  uiScale: number;
  /** What is shown around the picture when it does not fill the canvas: the current picture blurred and spread to fill / a plain color */
  backdrop: "blur" | "plain";
  /** Check for updates automatically after startup (shell app/Updates.cs, at most once a day); the shell reads this item itself (Settings.UpdateCheck) */
  updateCheck: boolean;

  // Annotations
  defaultCategory: AnnotationCategory;
  /** Pop up the input box automatically after a mark is drawn */
  autoCompose: boolean;
  /** Pause a video when an annotation tool is chosen on it */
  pauseOnAnnotate: boolean;
  /** Hold-to-use mode: holding C / R / B / A uses that tool temporarily and releasing returns to Select (hold.ts). Off by default and takes effect only when turned on in Settings */
  holdTools: boolean;
  /** Also show resolved notes on the canvas (faded) */
  showResolved: boolean;
  markColor: string;
  /** Mark line width (screen pixels) */
  markWidth: number;
  /** What the notes panel lists: the item on the canvas / the whole project it belongs to (with a multi-selection on the left, the selected ones are listed temporarily) */
  panelScope: "material" | "project";
  /** The notes panel also lists resolved notes (done / won't fix) */
  panelResolved: boolean;
  /** Sections filtered out of the notes panel (its funnel menu): canvas marks / timestamped comments / overall comments / older versions. Folder comments count as overall comments. Never everything is filtered out */
  panelHidden: NoteSection[];
  /** A video starts over after reaching the end (the control bar button, Ctrl+L and the menu's Playback all change it, so it is remembered) */
  loop: boolean;
  /** A video's volume 0–1 and mute: kept across videos and restarts (remembering only mute, and forgetting it on the next video, would be wrong) */
  volume: number;
  muted: boolean;

  // Notes files (REVIEW.md; a snapshot is always generated for every note)
  reviewIncludeResolved: boolean;
  /** Longest side of a snapshot, 0 = original size */
  snapshotMax: number;
  snapshotFormat: "png" | "jpeg";

  // Items
  kinds: Record<MaterialKind, boolean>;
  /** Folders also list the less common formats (TIFF, HEIC, ICO, APNG, JFIF, MKV) and the context menu offers them; the shell reads this (Settings.MoreFormats) */
  moreFormats: boolean;
  skipDirs: string[];
  initialSelect: "first" | "firstOpen";
  /** The library lists only items with open notes (so the ones to change are easy to find once the list is long) */
  libraryPending: boolean;
  /**
   * "New" in the library: since = from when each folder entry (key keyOf(path)) counts as new (the moment it was first seen, or "mark all as seen", in milliseconds);
   * seen = items that appeared after that and have already been opened and viewed (keyOf(path)). Not a setting; "Restore Defaults" leaves it alone
   */
  fresh: { since: Record<string, number>; seen: string[] };
  /** The onboarding tour and hints already seen (onboarding.ts: tour, hint.copy, hint.video, hint.screenAccess). Not a setting; "Restore Defaults" leaves it alone */
  onboarding: string[];

  // Handing off to AI (the copied content is generated by core's renderHandoff, with the note text written into it directly)
  /** A sentence appended at the end of every copy for AI, such as "re-export a new version when done"; empty = nothing appended */
  promptExtra: string;
}

/**
 * Settings that have been removed: when read they are dropped and not written back: the switches "write into project instructions", "export notes bundle" and "generate REVIEW.md automatically";
 * the prompt template (it used to copy just one sentence pointing at REVIEW.md, and now the note text is written in directly, replaced by "the sentence appended every time");
 * "AI can mark notes as done when it finishes" (cliShim, no longer called AI write-back of status); and "generate a snapshot for every note" (snapshots: always generated,
 * since agents cannot watch video or read coordinates well, and turning it off brings no benefit)
 */
const DROPPED_KEYS = ["agentFiles", "agentBlock", "exportIncludeMaterials", "writeReview", "promptTemplate", "cliShim", "snapshots"];

