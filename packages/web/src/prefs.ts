/**
 * Not items on the Settings pages but state adjusted on the fly and things remembered: "Restore Defaults" leaves them alone (the confirm dialog names the four pages General, Annotations, Copying and Advanced).
 * The notes panel's scope, filter and "show resolved", the library's "only items with open notes", volume and mute, "New" in the library, and the onboarding tour and hints already seen
 */
export const NOT_SETTINGS: (keyof Prefs)[] = [
  "panelScope",
  "panelResolved",
  "panelHidden",
  "libraryPending",
  "volume",
  "muted",
  "fresh",
  "onboarding",
];

/**
 * The version written to the settings file: keep only the items that differ from the defaults (unrecognized items are kept as they are). Items that were never changed are not written,
 * so when a later version changes a default, people who never changed it follow the new one (writing all the defaults at first launch would freeze them forever).
 * The few items the shell reads itself (kinds, moreFormats, skipDirs, markColor, defaultCategory, promptExtra) use the same defaults when absent (Settings.cs)
 */
export function storedPrefs(prefs: Prefs): Record<string, unknown> {
  const defaults = DEFAULT_PREFS as unknown as Record<string, unknown>;
  return Object.fromEntries(
    Object.entries(prefs).filter(([k, v]) => !(k in defaults) || JSON.stringify(v) !== JSON.stringify(defaults[k])),
  );
}

/** Settings that can only take these values: any other value (broken by hand editing, or added by a later version) falls back to the default */
const CHOICES: Partial<Record<keyof Prefs, readonly unknown[]>> = {
  backdrop: ["blur", "plain"],
  defaultCategory: ["change", "remove", "add", "question"],
  panelScope: ["material", "project"],
  snapshotFormat: ["png", "jpeg"],
  initialSelect: ["first", "firstOpen"],
};
/** Ranges of numbers: out-of-range values are clamped (the interface size is written into the CSS zoom, and 0 or a negative value would make the whole interface vanish) */
const RANGES: Partial<Record<keyof Prefs, [number, number]>> = {
  uiScale: [0.5, 2],
  markWidth: [0.5, 8],
  snapshotMax: [0, 16384],
  volume: [0, 1],
};

/**
 * Merge the stored settings with the defaults: when new settings are added later, old settings files keep working.
 * Every item is validated against the type of its default, and a wrong type or unrecognized value falls back to the default (validating only the mark color would let a `skipDirs` that is not an array
 * break the Settings page and a `uiScale` of 0 shrink the whole interface away; this only happens when the settings file is edited by hand)
 */
export function mergePrefs(saved: Partial<Prefs> | null | undefined): Prefs {
  if (!saved || typeof saved !== "object") return DEFAULT_PREFS;
  const merged = { ...DEFAULT_PREFS } as Record<string, unknown>;
  const raw = saved as Record<string, unknown>;
  for (const [k, def] of Object.entries(DEFAULT_PREFS)) {
    const v = raw[k];
    if (v === undefined) continue;
    const choices = CHOICES[k as keyof Prefs];
    if (k === "fresh") merged[k] = mergeFresh(v);
    else if (choices) merged[k] = choices.includes(v) ? v : def;
    else if (typeof def === "number") {
      const range = RANGES[k as keyof Prefs];
      merged[k] = typeof v === "number" && Number.isFinite(v) ? (range ? Math.min(range[1], Math.max(range[0], v)) : v) : def;
    } else if (Array.isArray(def)) merged[k] = Array.isArray(v) ? v.filter((x) => typeof x === "string" && x.trim() !== "") : def;
    else if (typeof def === "object") {
      // kinds: each type is checked on its own, and one that is not a boolean uses the default
      const obj = v && typeof v === "object" && !Array.isArray(v) ? (v as Record<string, unknown>) : {};
      merged[k] = Object.fromEntries(Object.entries(def).map(([kk, dv]) => [kk, typeof obj[kk] === "boolean" ? obj[kk] : dv]));
    } else merged[k] = typeof v === typeof def ? v : def;
  }
  // Unrecognized items are kept as they are (added by a later version, and not lost when written back); removed old items are dropped
  for (const [k, v] of Object.entries(raw)) if (!(k in DEFAULT_PREFS)) merged[k] = v;
  for (const k of DROPPED_KEYS) delete merged[k];
  return finish(merged as unknown as Prefs);
}

/** Each entry in fresh is checked on its own: start times must be numbers and seen items strings, and anything else is dropped (so a hand-edited mistake does not mark the whole library "New" or break it) */
function mergeFresh(v: unknown): Prefs["fresh"] {
  const o = v && typeof v === "object" && !Array.isArray(v) ? (v as Record<string, unknown>) : {};
  const since = o.since && typeof o.since === "object" && !Array.isArray(o.since) ? (o.since as Record<string, unknown>) : {};
  return {
    since: Object.fromEntries(Object.entries(since).filter(([, t]) => typeof t === "number" && Number.isFinite(t))) as Record<
      string,
      number
    >,
    seen: Array.isArray(o.seen) ? o.seen.filter((x): x is string => typeof x === "string") : [],
  };
}

function finish(merged: Prefs): Prefs {
  // The mark color is interpolated into SVG (AnnotationLayer), so even a settings file broken by hand editing must not smuggle anything else in
  if (!isMarkColor(merged.markColor)) merged.markColor = DEFAULT_PREFS.markColor;
  // The notes panel filter: only the known sections count; if everything is filtered out (by hand editing), nothing is filtered, so the notes panel never ends up empty
  const hidden = NOTE_SECTIONS.filter((s) => merged.panelHidden.includes(s));
  merged.panelHidden = hidden.length < NOTE_SECTIONS.length ? hidden : [];
  return merged;
}

