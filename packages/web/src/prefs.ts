export interface PrefsApi {
  prefs: Prefs;
  setPrefs: (patch: Partial<Prefs>) => void;
}

export const PrefsContext = createContext<PrefsApi>({ prefs: DEFAULT_PREFS, setPrefs: () => {} });
export const usePrefs = () => useContext(PrefsContext);
